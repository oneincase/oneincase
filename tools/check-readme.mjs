#!/usr/bin/env node
/**
 * README link checker.
 *
 *  - extracts every <img src>, <source srcset> and markdown link from README.md
 *  - classifies remote vs local, resolves local paths on disk
 *  - HTTP-checks every remote image (the ones that actually render on GitHub)
 *
 * Run:  node tools/check-readme.mjs [--no-net]
 */

import { readFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const md = readFileSync(join(ROOT, "README.md"), "utf8");
const noNet = process.argv.includes("--no-net");

// Entity map for the few HTML entities we use inside URLs.
const decode = (s) =>
  s.replaceAll("&amp;", "&")
    .replaceAll("&#183;", "·")
    .replaceAll("&#215;", "×");

const found = [];
for (const m of md.matchAll(/src="([^"]+)"/g)) found.push({ kind: "img src", url: decode(m[1]) });
for (const m of md.matchAll(/srcset="([^"]+)"/g)) found.push({ kind: "source srcset", url: decode(m[1]) });
for (const m of md.matchAll(/\]\((https?:\/\/[^)\s]+)\)/g)) found.push({ kind: "md link", url: decode(m[1]) });

const seen = new Map();
for (const f of found) if (!seen.has(f.url)) seen.set(f.url, f);

const remoteImages = [];
const remotePages = [];
const localPaths = [];
// Assets that live on this repo's `output` branch (generated by CI, not in the
// main tree) and therefore may legitimately trail the README until the next run.
let outputRefs = new Set();
try {
  const { execSync } = await import("node:child_process");
  outputRefs = new Set(
    execSync("git ls-tree -r --name-only origin/output", { cwd: ROOT, encoding: "utf8" })
      .split("\n")
      .map((s) => s.trim())
      .filter(Boolean),
  );
} catch {
  /* no output branch yet — nothing to exempt */
}
void outputRefs;

for (const [url, meta] of seen) {
  if (/^https?:/.test(url)) {
    (meta.kind === "md link" ? remotePages : remoteImages).push(url);
  } else {
    localPaths.push(url);
  }
}

console.log(`README: ${md.split("\n").length} lines`);
console.log(`unique urls: ${seen.size}`);
console.log(`  remote images: ${remoteImages.length}`);
console.log(`  remote links : ${remotePages.length}`);
console.log(`  local refs   : ${localPaths.length}\n`);

// Remote assets produced by our own snake workflow: absent on `output` until CI
// runs, so a 404 is expected there and is not a README defect.
const isOutputBranchAsset = (url) => {
  const m = url.match(/^https:\/\/raw\.githubusercontent\.com\/oneincase\/oneincase\/output\/(.+)$/);
  return Boolean(m && !outputRefs.has(m[1]));
};

let bad = 0;

console.log("── local refs ──");
for (const p of localPaths) {
  const abs = resolve(ROOT, p.replace(/^\.\//, ""));
  const ok = existsSync(abs);
  if (!ok) bad += 1;
  console.log(`${ok ? "OK  " : "MISS"}  ${p}`);
}

if (noNet) {
  console.log("\n(--no-net: skipped remote checks)");
  process.exit(bad ? 1 : 0);
}

async function head(url) {
  // GitHub's camo proxy fetches with no referer; mimic a plain GET.
  const res = await fetch(url, {
    redirect: "follow",
    headers: { "user-agent": "Mozilla/5.0 (readme-asset-check)" },
  });
  const ct = res.headers.get("content-type") || "";
  return { status: res.status, ct };
}

console.log("\n── remote images ──");
const results = await Promise.all(
  remoteImages.map(async (url) => {
    try {
      const r = await head(url);
      return { url, ...r };
    } catch (e) {
      return { url, status: 0, ct: `ERR ${e.message}` };
    }
  }),
);
for (const r of results) {
  const pendingOutput = r.status === 404 && isOutputBranchAsset(r.url);
  const ok = pendingOutput || (r.status === 200 && /image|svg|xml/i.test(r.ct + " svg xml"));
  if (!ok) bad += 1;
  const verdict = ok ? (pendingOutput ? "WAIT" : "OK  ") : "BAD ";
  console.log(`${verdict}  ${String(r.status).padStart(4)}  ${r.ct.slice(0, 28).padEnd(28)}  ${r.url.slice(0, 118)}`);
}

console.log("\n── remote links ──");
const links = await Promise.all(
  remotePages.map(async (url) => {
    try {
      return { url, ...(await head(url)) };
    } catch (e) {
      return { url, status: 0, ct: `ERR ${e.message}` };
    }
  }),
);
for (const r of links) {
  const ok = r.status >= 200 && r.status < 400;
  if (!ok) bad += 1;
  console.log(`${ok ? "OK  " : "BAD "}  ${String(r.status).padStart(4)}  ${r.url.slice(0, 110)}`);
}

// ── monospace alignment of fenced ```text blocks ────────────────────────────
// CJK is double-width and emoji are double-width in most terminal/monospace
// renderers, so a naive `padEnd` looks aligned in an editor and ragged on
// GitHub. Recompute with display width and require a shared `|` column.
const displayWidth = (s) => {
  let w = 0;
  for (const ch of s) {
    const cp = ch.codePointAt(0);
    if (cp === 0xfe0f || cp === 0x200d) continue; // variation selector / ZWJ
    const wide =
      (cp >= 0x1100 && cp <= 0x115f) ||
      (cp >= 0x2e80 && cp <= 0xa4cf) ||
      (cp >= 0xac00 && cp <= 0xd7a3) ||
      (cp >= 0xf900 && cp <= 0xfaff) ||
      (cp >= 0xfe30 && cp <= 0xfe6f) ||
      (cp >= 0xff00 && cp <= 0xff60) ||
      (cp >= 0xffe0 && cp <= 0xffe6) ||
      (cp >= 0x1f300 && cp <= 0x1faff) ||
      (cp >= 0x2600 && cp <= 0x27bf);
    w += wide ? 2 : 1;
  }
  return w;
};

console.log("\n── monospace blocks ──");
const blocks = [...md.matchAll(/```text\n([\s\S]*?)```/g)].map((m) => m[1].replace(/\n$/, ""));
blocks.forEach((block, i) => {
  const lines = block.split("\n").filter((l) => l.includes("|"));
  if (lines.length >= 2) {
    const cols = lines.map((l) => displayWidth(l.slice(0, l.indexOf("|"))));
    const uniq = [...new Set(cols)];
    const ok = uniq.length === 1;
    if (!ok) bad += 1;
    console.log(
      `${ok ? "OK  " : "BAD "}  block ${i + 1}: ${lines.length} aligned rows, "|" at display width ${uniq.join(",")}`,
    );
    return;
  }
  // Box-drawing panels: every line must have the same display width, and the
  // leading/trailing glyph must be the matching pair.
  const boxed = block.split("\n").filter((l) => /^[┌│└]/.test(l));
  if (boxed.length >= 2) {
    const widths = [...new Set(boxed.map(displayWidth))];
    const ok = widths.length === 1;
    if (!ok) bad += 1;
    console.log(
      `${ok ? "OK  " : "BAD "}  block ${i + 1}: box panel ${boxed.length} rows, width ${widths.join(",")}`,
    );
    return;
  }
  console.log(`OK    block ${i + 1}: ${block.split("\n").length} lines (no aligned columns)`);
});

// ── README <-> snake workflow consistency ───────────────────────────────────
// The snake assets are not in the main tree; CI writes them to the `output`
// branch. A palette that the workflow does not emit is a 404 on a live profile
// page, so assert every referenced variant is actually generated.
console.log("\n── snake workflow ──");
try {
  const wfPath = join(ROOT, ".github", "workflows", "snake.yml");
  const wf = readFileSync(wfPath, "utf8");
  const wfLines = wf.split("\n");
  const start = wfLines.findIndex((l) => /^\s*outputs:\s*\|-?\s*$/.test(l));
  const blockLines = [];
  if (start !== -1) {
    const indent = wfLines[start].match(/^\s*/)[0].length;
    for (let i = start + 1; i < wfLines.length; i += 1) {
      const line = wfLines[i];
      if (!line.trim()) continue;
      if (line.match(/^\s*/)[0].length <= indent) break;
      blockLines.push(line.trim());
    }
  }
  const generated = new Set(blockLines.map((l) => l.split("?")[0].replace(/^dist\//, "")));
  const referenced = [
    ...new Set(
      md
        .match(/raw\.githubusercontent\.com\/oneincase\/oneincase\/output\/([^"'\s)]+)/g)
        ?.map((u) => u.split("/output/")[1]) ?? [],
    ),
  ];
  const orphans = referenced.filter((f) => !generated.has(f));
  const unused = [...generated].filter((f) => !referenced.includes(f));
  if (orphans.length) bad += orphans.length;
  console.log(`${orphans.length ? "BAD " : "OK  "}  workflow generates ${generated.size}: ${[...generated].join(", ")}`);
  console.log(`${orphans.length ? "BAD " : "OK  "}  README references  ${referenced.length}: ${referenced.join(", ")}`);
  if (orphans.length) console.log(`      referenced but NOT generated: ${orphans.join(", ")}`);
  if (unused.length) console.log(`      generated but unused: ${unused.join(", ")}`);
} catch (e) {
  bad += 1;
  console.log(`BAD   could not check snake workflow: ${e.message}`);
}

console.log(bad === 0 ? "\nALL CHECKS PASSED" : `\n${bad} PROBLEM(S)`);
process.exit(bad ? 1 : 0);